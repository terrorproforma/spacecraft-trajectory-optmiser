#!/bin/bash
set -euo pipefail
source "$HOME/spacepdhcg/env.sh"
cd "$HOME/spacepdhcg/v2"
export PATH="$PWD/.venv/bin:$PATH" PYTHONPATH="$PWD/src"
# Only touch the tree after the sweep has finished (it asserts a clean tree at start; results/ is ignored).
test -z "$(pgrep -f 'v2_deferred.sh')" || { echo "sweep still running: refuse"; exit 3; }
git status --short
git diff --quiet -- src/spacepdhcg/literature/gpu_preflight.py && python3 "$HOME/s/patch_preflight.py"
python3 "$HOME/s/patch_preflight2.py" || true
git diff --stat -- src tests
ruff check src/spacepdhcg/literature/gpu_preflight.py tests/test_literature_gpu_preflight.py
ruff format --check src/spacepdhcg/literature/gpu_preflight.py tests/test_literature_gpu_preflight.py || { ruff format src/spacepdhcg/literature/gpu_preflight.py tests/test_literature_gpu_preflight.py; }
CUDA_VISIBLE_DEVICES="" python -m pytest -q -p no:cacheprovider tests/test_literature_gpu_preflight.py tests/test_gpu_deferred_manifest.py
export GIT_AUTHOR_NAME=SpacePDHCG-Integration GIT_AUTHOR_EMAIL=integration@spacepdhcg.local
export GIT_COMMITTER_NAME=SpacePDHCG-Integration GIT_COMMITTER_EMAIL=integration@spacepdhcg.local
# The gpu-run rewrote the report twins; keep them out of this fix commit (they are re-generated by the rerun).
git add src/spacepdhcg/literature/gpu_preflight.py tests/test_literature_gpu_preflight.py
git commit -q -m "fix(literature): GPU preflight must not count its own process as a foreign device holder

On native Linux nvidia-smi lists compute processes. Once the first target of a
multi-target 'spacepdhcg literature gpu-run' opened a CUDA context, the preflight
inside every later target saw the gpu-run process itself and refused
('other compute processes hold the device (pid <self>)'), so
blackmore-2010-pd3-case1 was recorded as 'deferred' although the device was free.
WSL nvidia-smi never lists compute apps, which hid this on the RTX 5090 host.

Found by the H100 deferred GPU validation sweep (results/gpu/h100-deferred-3373988)."
git log --oneline -2
git status --short
