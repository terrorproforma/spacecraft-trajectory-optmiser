namespace spacepdhcg::scvx {

enum class LowThrustTransferClass {
    coast_reference,
    radius_raise,
    plane_change,
    combined,
};

[[nodiscard]] inline LowThrustTransferClass low_thrust_transfer_class(
    const std::string_view name
) {
    if (name == "coast_reference") {
        return LowThrustTransferClass::coast_reference;
    }
    if (name == "radius_raise") {
        return LowThrustTransferClass::radius_raise;
    }
    if (name == "plane_change") {
        return LowThrustTransferClass::plane_change;
    }
    if (name == "combined") {
        return LowThrustTransferClass::combined;
    }
    throw std::invalid_argument("unknown frozen low-thrust transfer class");
}

[[nodiscard]] inline std::string_view low_thrust_transfer_class_name(
    const LowThrustTransferClass transfer
) noexcept {
    switch (transfer) {
        case LowThrustTransferClass::coast_reference:
            return "coast_reference";
        case LowThrustTransferClass::radius_raise:
            return "radius_raise";
        case LowThrustTransferClass::plane_change:
            return "plane_change";
        case LowThrustTransferClass::combined:
            return "combined";
    }
    return "unknown";
}

namespace low_thrust_benchmark_detail {

using Vector3 = std::array<double, 3U>;

[[nodiscard]] inline Vector3 cross(const Vector3& left, const Vector3& right) noexcept {
    return {
        left[1U] * right[2U] - left[2U] * right[1U],
        left[2U] * right[0U] - left[0U] * right[2U],
        left[0U] * right[1U] - left[1U] * right[0U],
    };
}

[[nodiscard]] inline Vector3 normalised(const Vector3& value) {
    const auto norm = std::sqrt(
        value[0U] * value[0U] + value[1U] * value[1U]
        + value[2U] * value[2U]
    );
    if (!std::isfinite(norm) || norm <= 0.0) {
        throw std::invalid_argument("low-thrust transfer direction is singular");
    }
    return {value[0U] / norm, value[1U] / norm, value[2U] / norm};
}

[[nodiscard]] inline Vector3 thrust_direction(
    const dynamics::LowThrustState& state,
    const LowThrustTransferClass transfer
) {
    const Vector3 position{state[0U], state[1U], state[2U]};
    const Vector3 velocity{state[3U], state[4U], state[5U]};
    const auto radial = normalised(position);
    const auto normal = normalised(cross(position, velocity));
    const auto tangent = normalised(cross(normal, radial));
    if (transfer == LowThrustTransferClass::radius_raise) {
        return tangent;
    }
    if (transfer == LowThrustTransferClass::plane_change) {
        return normal;
    }
    return normalised({
        tangent[0U] + normal[0U],
        tangent[1U] + normal[1U],
        tangent[2U] + normal[2U],
    });
}

}  // namespace low_thrust_benchmark_detail

/// Construct the deterministic physical target associated with one frozen P1-E transfer class.
///
/// The qualification reference remains the coast trajectory. Non-coast targets are generated by
/// nonlinear RK4 propagation with a feasible 15%-throttle steering law, so the target is reachable
/// without inventing an initial-state "dispersion" coordinate that P1-E does not define.
[[nodiscard]] inline LowThrustReference make_low_thrust_transfer_target(
    const dynamics::LowThrustTwoBodyModel& model,
    const dynamics::LowThrustState& initial,
    const std::size_t intervals,
    const double step_seconds,
    const LowThrustTransferClass transfer
) {
    if (intervals < 2U || !std::isfinite(step_seconds) || step_seconds <= 0.0) {
        throw std::invalid_argument("low-thrust transfer grid is invalid");
    }
    std::vector<dynamics::LowThrustState> states(intervals + 1U);
    std::vector<dynamics::LowThrustControl> controls(intervals);
    states.front() = initial;
    const auto throttle = transfer == LowThrustTransferClass::coast_reference
                              ? 0.0
                              : 0.15 * model.config().maximum_thrust;
    for (std::size_t interval = 0U; interval < intervals; ++interval) {
        dynamics::LowThrustControl control{0.0, 0.0, 0.0, throttle};
        if (throttle > 0.0) {
            const auto direction =
                low_thrust_benchmark_detail::thrust_direction(states[interval], transfer);
            for (std::size_t component = 0U; component < 3U; ++component) {
                control[component] = throttle * direction[component];
            }
        }
        controls[interval] = control;
        states[interval + 1U] = model.rk4_step(states[interval], control, step_seconds);
    }
    return {std::move(states), std::move(controls)};
}

}  // namespace spacepdhcg::scvx
