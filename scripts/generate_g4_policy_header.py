#!/usr/bin/env python3
"""Generate/check the C++ G4 constants derived from the frozen JSON policy."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any


def _number(value: Any) -> str:
    if isinstance(value, int):
        return str(value)
    return f"{float(value):.17g}"


def render(policy_path: Path) -> str:
    raw = policy_path.read_bytes()
    policy = json.loads(raw)
    adaptive = policy["policies"]["adaptive"]
    phases = adaptive["phase_ceilings"]
    limits = adaptive["phase_iteration_limits"]
    resolve = policy["resolve_policy"]
    trust = policy["trust_policy"]
    tiers = policy["quality_tiers"]
    digest = hashlib.sha256(raw).hexdigest()
    return f"""#pragma once

// Generated by scripts/generate_g4_policy_header.py. Do not edit by hand.
#include <array>
#include <cstddef>
#include <string_view>

namespace spacepdhcg::scvx::g4_policy {{

inline constexpr std::string_view sha256 = "{digest}";
inline constexpr double epsilon_max = {_number(adaptive["epsilon_max"])};
inline constexpr double epsilon_floor = {_number(adaptive["epsilon_floor"])};
inline constexpr double epsilon_0 = {_number(adaptive["epsilon_0"])};
inline constexpr double coefficient = {_number(adaptive["coefficient"])};
inline constexpr double alpha = {_number(adaptive["alpha"])};
inline constexpr double gamma = {_number(adaptive["gamma"])};
inline constexpr double repair_ceiling = {_number(phases["repair"])};
inline constexpr double progress_ceiling = {_number(phases["progress"])};
inline constexpr double refinement_ceiling = {_number(phases["refinement"])};
inline constexpr double polish_ceiling = {_number(phases["polish"])};
inline constexpr std::size_t repair_iterations = {limits["repair"]}U;
inline constexpr std::size_t progress_iterations = {limits["progress"]}U;
inline constexpr std::size_t refinement_iterations = {limits["refinement"]}U;
inline constexpr std::size_t polish_iterations = {limits["polish"]}U;
inline constexpr double resolve_trigger_multiple = {
        _number(resolve["trigger_multiple_of_requested_tolerance"])
    };
inline constexpr double resolve_refinement_factor = {_number(resolve["refinement_factor"])};
inline constexpr double resolve_minimum_tolerance = {
        _number(resolve["minimum_resolve_tolerance"])
    };
inline constexpr std::size_t maximum_resolves = {
        resolve["maximum_resolves_per_outer_iteration"]
    }U;
inline constexpr double trust_acceptance = {_number(trust["acceptance_threshold"])};
inline constexpr double trust_initial = {_number(trust["initial_radius"])};
inline constexpr double trust_minimum = {_number(trust["minimum_radius"])};
inline constexpr double trust_maximum = {_number(trust["maximum_radius"])};
inline constexpr double trust_shrink = {_number(trust["shrink_factor"])};
inline constexpr double trust_expand = {_number(trust["expansion_factor"])};
inline constexpr double trust_strong_agreement = {_number(trust["strong_agreement"])};
inline constexpr double trust_boundary_fraction = {_number(trust["near_boundary_fraction"])};
inline constexpr std::array<double, 4> quality_tolerances{{
    {_number(tiers["coarse"])},
    {_number(tiers["medium"])},
    {_number(tiers["tight"])},
    {_number(tiers["ipm"])},
}};

}}  // namespace spacepdhcg::scvx::g4_policy
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--policy", type=Path, default=Path("benchmarks/g4_policy.json"))
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("cpp/include/spacepdhcg/scvx/g4_policy.generated.hpp"),
    )
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    expected = render(arguments.policy)
    if arguments.check:
        current = (
            arguments.output.read_text(encoding="utf-8")
            if arguments.output.exists()
            else None
        )
        if current != expected:
            raise SystemExit("generated G4 policy header is stale")
        return 0
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
