"""Prepare/verify immutable v632 evidence using only saved bytes and stdlib.

This script has no subprocess, network, native-library, solver, or propagation
entry point. Build mode requires a byte-pinned plan supplied after experiments
finish; it refuses a pending doc or reports and never overwrites a package.

Plan schema (all paths repository-relative, all files explicit):
{
  "schema": "gpu-mass-merit-v632-plan-v1",
  "doc_sha256": "...",
  "build_manifest_sha256": "...",
  "unit_report": "build/performance/gpu-mass-merit-v632/gpu-tests-b/report.json",
  "mission_report": "build/performance/mass-merit-return-v632/output/report.json",
  "files": {"relative/path": {"bytes": 123, "sha256": "..."}},
  "omitted_files": {"exact generated cache path": {"bytes": 123, "sha256": "...", "reason": "generated bytecode"}}
}
The files map must include each build stage log and source archive, unit report
and raw process logs, the final mission ready map and every non-binary member it
indexes, plus all terminal raw outputs/reviews selected by root. No omission is
silently made. Failed outcomes are retained and do not become passing claims.
The sealed diagnosis and its prior-source provenance are added automatically.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import tarfile
import tempfile
import zipfile

SCHEMA = "gpu-mass-merit-v632-v1"
DIAG = "build/performance/terminal-mass-merit-v632"
DIAG_SHA = "5da2a3cb7def81b6d6d50bf5a1d9e6567f4da1e0d8a558abc25e45090be0f826"
BUILD = "build/performance/gpu-mass-merit-v632"
MISSION = "build/performance/mass-merit-return-v632"
PRIOR = "build/performance/gpu-scaled-zoh-v631"
PRIOR_MANIFEST_SHA = "b92df5cc06f0119e0958b85935334b82910967f580f0d02bab2bde8d39702e11"
PRIOR_ARCHIVE_SHA = "ff90bc2b1b9a66c8d37abc933990a55d9327bd61ff15eb610940d41b32372ab0"
OWNED = ("cpp/cuda/src/gtoc12_scvx.cu", "cpp/cuda/tests/gtoc12_scvx_test.cu",
         "cpp/cuda/tests/gtoc12_device_refresh_test.cu")
DOC = "docs/GPU_MASS_MERIT.md"
SELF = "build/performance/gpu-mass-merit-v632-publish/package.py"
FINAL = "results/local/2026-09-09/gpu-mass-merit-v632"
CACHE_OMISSIONS = {BUILD + "/gpu-tests-" + attempt + "/__pycache__/process_guard.cpython-312.pyc"
                   for attempt in ("a", "b")}
FORBIDDEN = {".exe", ".dll", ".so", ".o", ".obj", ".a", ".lib", ".pdb", ".pyc", ".cubin", ".fatbin", ".ptx"}
KEY = re.compile(rb"(?m)^\s*-----BEGIN (?:[A-Z0-9 ]* )?PRIVATE KEY-----")


def check(condition, message):
    if not condition:
        raise ValueError(message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def record(raw):
    return {"bytes": len(raw), "sha256": sha(raw)}


def safe_name(name):
    p = PurePosixPath(name)
    check(bool(name) and not p.is_absolute() and "\\" not in name and ":" not in name,
          "Unsafe member: " + name)
    check(all(v not in {"", ".", "..", ".git", "__pycache__", ".pytest_cache", ".ruff_cache"}
              for v in name.split("/")), "Unsafe path component: " + name)
    check(p.suffix.lower() not in FORBIDDEN, "Compiled/cache member: " + name)
    return p


def inspect(raw, name, budget, depth=0):
    safe_name(name)
    budget[0] += len(raw)
    check(budget[0] <= 512 * 1024 * 1024 and depth <= 6, "Archive safety budget")
    check(not raw.startswith((b"\x7fELF", b"MZ")) and not KEY.search(raw), "Binary/private key: " + name)
    if name.endswith((".tar.gz", ".tgz", ".tar")):
        with tarfile.open(fileobj=io.BytesIO(raw), mode="r:*") as archive:
            seen = set()
            for member in archive:
                check(member.isfile() and member.name not in seen, "Tar link/type/duplicate: " + member.name)
                seen.add(member.name)
                check(0 <= member.size <= 128 * 1024 * 1024, "Oversized tar member")
                inspect(archive.extractfile(member).read(), member.name, budget, depth + 1)
    elif name.endswith((".zip", ".npz")):
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            check(len(archive.namelist()) == len(set(archive.namelist())), "Nested ZIP duplicates")
            for info in archive.infolist():
                mode = info.external_attr >> 16
                check(not info.is_dir() and not stat.S_ISLNK(mode), "ZIP link/directory")
                check(0 <= info.file_size <= 128 * 1024 * 1024, "Oversized ZIP member")
                inspect(archive.read(info), info.filename, budget, depth + 1)


def source_archive(raw, manifest):
    actual = {}
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as archive:
        for member in archive:
            safe_name(member.name)
            check(member.isfile() and member.name not in actual, "Source member type/duplicate")
            actual[member.name] = sha(archive.extractfile(member).read())
    check(actual == manifest["sources"], "Archived source map mismatch")
    check(sha(raw) == manifest["source_archive_sha256"], "Source archive hash mismatch")
    tree = sha("".join(name + ":" + value + "\n" for name, value in manifest["sources"].items()).encode())
    check(tree == manifest["source_tree_sha256"], "Source tree hash mismatch")
    return actual


def semantics(files, metadata):
    decode = lambda name: json.loads(files[name])
    old = decode(PRIOR + "/manifest.json")
    new = decode(BUILD + "/manifest.json")
    check(sha(files[PRIOR + "/manifest.json"]) == PRIOR_MANIFEST_SHA, "Prior manifest changed")
    check(sha(files[PRIOR + "/source.tar.gz"]) == PRIOR_ARCHIVE_SHA, "Prior source changed")
    check(sha(files[BUILD + "/manifest.json"]) == metadata["build_manifest_sha256"], "Final build pin changed")
    check(new["complete"] and new["passed"] and new["base_commit"] == "cd8d6eb27f08f6966faaddac56e360b615a92256", "Build not passed/final/on intended base")
    before = source_archive(files[PRIOR + "/source.tar.gz"], old)
    after = source_archive(files[BUILD + "/source.tar.gz"], new)
    changed = {name for name in set(before) | set(after) if before.get(name) != after.get(name)}
    check(changed == set(OWNED), "Source delta must be exactly three owned CUDA overlays")
    check(set(new["owned"]) == set(OWNED), "Build ownership map differs")
    for name in OWNED:
        check(sha(files[name]) == after[name] == new["owned_sha256"][name], "Root source bytes differ: " + name)
    for stage in new["stages"]:
        if "log_sha256" in stage:
            check(sha(files[BUILD + "/" + stage["name"] + ".log"]) == stage["log_sha256"], "Build log mismatch")
    for stage in old["stages"]:
        if stage["name"] in ("cpu-tests", "ruff"):
            check(sha(files[PRIOR + "/" + stage["name"] + ".log"]) == stage["log_sha256"], "Prior host validation log mismatch")
    host = {name: digest for name, digest in after.items() if name.startswith("src/spacepdhcg/")}
    check(host == {name: digest for name, digest in before.items() if name.startswith("src/spacepdhcg/")}, "Host source changed")
    check(len(host) == new["unchanged_host_validation"]["host_files"], "Prior host file count mismatch")
    check(sha(files[DIAG + "/index.json"]) == DIAG_SHA, "Sealed diagnosis changed")
    for name, pin in decode(DIAG + "/index.json")["files"].items():
        check(record(files[DIAG + "/" + name]) == pin, "Diagnosis file mismatch")
    ready = decode(MISSION + "/ready.json")
    for name, digest in ready["files"].items():
        check(sha(files[MISSION + "/" + name]) == digest, "Frozen mission member absent/changed: " + name)
    unit, mission = decode(metadata["unit_report"]), decode(metadata["mission_report"])
    check(unit.get("complete") is True and mission.get("complete") is True, "Run still pending")
    check(isinstance(mission.get("status"), str) and "pending" not in mission["status"].lower(), "Mission status pending")
    check(unit["manifest_sha256"] == metadata["build_manifest_sha256"], "Unit/core manifest mismatch")
    check(unit["source_tree_sha256"] == new["source_tree_sha256"], "Unit/source tree mismatch")
    unit_prefix = str(PurePosixPath(metadata["unit_report"]).parent)
    check(sha(files[unit_prefix + "/run.py"]) == unit["runner_sha256"], "Unit supervisor mismatch")
    check(sha(files[unit_prefix + "/process_guard.py"]) == unit["process_guard_sha256"], "Unit process guard mismatch")
    blocked = decode(BUILD + "/gpu-tests-a/report.json")
    check(blocked["complete"] and not blocked["passed"] and blocked["stages"] == []
          and "BlockingIOError" in blocked["error"], "Prior lock-busy outcome not preserved")
    for leaf, key in (("run.py", "runner_sha256"), ("process_guard.py", "process_guard_sha256")):
        check(sha(files[BUILD + "/gpu-tests-a/" + leaf]) == blocked[key], "Lock-busy source mismatch")
    check(unit["optimizer_calls"] == 0, "Native unit scope changed")
    if unit.get("passed"):
        check(len(unit["stages"]) == 6 and unit["final_cleanup"]["verified_empty"]
              and not unit["final_compute_inventory"], "Native unit count/final cleanup mismatch")
    for stage in unit["stages"]:
        if "log_sha256" in stage:
            check(sha(files[unit_prefix + "/" + stage["name"] + ".log"]) == stage["log_sha256"], "Unit log mismatch")
        if unit.get("passed"):
            check(stage["exit_code"] == 0 and stage["cleanup"]["verified_empty"]
                  and not stage["compute_after"], "Passing unit report has failed stage")
    profile = decode(MISSION + "/profile.json")
    check(profile["library"]["sha256"] == new["outputs"]["library"]["sha256"], "Mission/core binary mismatch")
    launch = decode(MISSION + "/output/launch-report.json")
    check(launch["complete"] and launch["ready_sha256"] == sha(files[MISSION + "/ready.json"]), "Mission launch/ready mismatch")
    check(launch["passed"] and launch["exit_code"] == 0 and launch["child_exit_after_cleanup"] == 0
          and launch["owned_descendant_cleanup"]["verified_empty"]
          and not launch["compute_processes_after_cleanup"], "Mission process accounting/cleanup failed")
    check(launch["core_source_archive_validation"]["sha256"] == new["source_archive_sha256"], "Mission/core archive mismatch")
    saved_audit = decode(MISSION + "/saved-audit.json")
    check(saved_audit["passed"] and saved_audit["new_GPU_calls"] == 0
          and saved_audit["new_solver_calls"] == 0 and saved_audit["new_orbital_propagations"] == 0,
          "Saved mission audit failed or changed scope")
    check(saved_audit["report_sha256"] == sha(files[metadata["mission_report"]])
          and saved_audit["launch_report_sha256"] == sha(files[MISSION + "/output/launch-report.json"]),
          "Saved mission audit/report mismatch")
    for name, pin in saved_audit["raw_output_files"].items():
        check(record(files[MISSION + "/output/" + name]) == pin, "Saved raw output binding mismatch: " + name)
    for name, digest in saved_audit["source_equation_hashes"].items():
        check(after[name] == digest, "Saved mass-equation source mismatch")
    check(b"V632_RESULTS_PENDING" not in files[DOC], "Doc still marks results pending")
    return {"build_passed": new["passed"], "source_members": len(after), "changed_sources": sorted(changed),
            "unit_passed": unit.get("passed"), "mission_status": mission["status"],
            "mission_native_iterations": mission.get("native_iterations"),
            "mission_native_solves_returned": mission.get("native_solves_returned"),
            "archive_verify_GPU_calls": 0, "archive_verify_solver_calls": 0, "archive_verify_propagations": 0}


def verify(package, index_sha=None, roundtrip=False):
    index_raw = (package / "index.json").read_bytes()
    if index_sha:
        check(sha(index_raw) == index_sha, "Index pin mismatch")
    index = json.loads(index_raw)
    check(index["schema"] == SCHEMA, "Wrong schema")
    check(set(index.get("omitted_files", {})) <= CACHE_OMISSIONS, "Unexpected omitted inputs")
    raw = (package / "evidence.zip").read_bytes()
    check(record(raw) == {"bytes": index["archive_bytes"], "sha256": index["archive_sha256"]}, "ZIP pin mismatch")
    for name, pin in index["top_files"].items():
        safe_name(name)
        check(record((package / name).read_bytes()) == pin, "Top file mismatch")
    files = {}
    budget = [0]
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        check(len(archive.namelist()) == len(set(archive.namelist())), "ZIP duplicates")
        check(set(archive.namelist()) == set(index["files"]), "ZIP/index member mismatch")
        for info in archive.infolist():
            check(not info.is_dir() and stat.S_ISREG(info.external_attr >> 16), "Nonregular member")
            data = archive.read(info)
            check(record(data) == index["files"][info.filename], "File pin mismatch: " + info.filename)
            inspect(data, info.filename, budget)
            files[info.filename] = data
    check(len(files) == index["file_count"] and sum(map(len, files.values())) == index["total_bytes"], "Count/bytes mismatch")
    result = semantics(files, index["bindings"])
    if roundtrip:
        with tempfile.TemporaryDirectory(prefix="mass-merit-v632-static-") as directory:
            base = Path(directory)
            for name, data in files.items():
                target = base.joinpath(*safe_name(name).parts)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
                check(target.read_bytes() == data, "Roundtrip changed bytes")
    return {"passed": True, "index_sha256": sha(index_raw), "archive_sha256": sha(raw),
            "file_count": len(files), "total_bytes": index["total_bytes"],
            "roundtrip_performed": roundtrip, **result}


def build(root, plan_path):
    plan_raw = plan_path.read_bytes()
    plan = json.loads(plan_raw)
    check(plan["schema"] == "gpu-mass-merit-v632-plan-v1", "Wrong plan schema")
    final = root / FINAL
    stage = root / "build/performance/gpu-mass-merit-v632-publish/assembly"
    check(not final.exists() and not stage.exists(), "Fresh final and assembly paths required")
    files = {}

    def add(name, pin=None):
        p = safe_name(name)
        path = root.joinpath(*p.parts)
        check(root == path.resolve().parents[len(p.parts) - 1], "Input outside repository")
        check(not any(parent.is_symlink() for parent in [path, *path.parents] if parent != root.parent), "Input symlink")
        raw = path.read_bytes()
        if pin:
            check(record(raw) == pin, "Input pin changed: " + name)
        check(name not in files or files[name] == raw, "Duplicate input conflict")
        files[name] = raw

    for name, pin in plan["files"].items():
        check(name.startswith((BUILD + "/", MISSION + "/")), "Plan file outside the two owned kits: " + name)
        add(name, pin)
    omitted = plan.get("omitted_files", {})
    check(set(omitted) <= CACHE_OMISSIONS, "Only the two declared generated guard caches may be omitted")
    for name, pin in omitted.items():
        path = root / name
        check(root in path.resolve().parents and not path.is_symlink(), "Unsafe omitted cache path")
        check(record(path.read_bytes()) == {"bytes": pin["bytes"], "sha256": pin["sha256"]}, "Omitted cache pin changed")
        check(bool(pin.get("reason")), "Omitted cache needs explicit reason")
    for name in (PRIOR + "/manifest.json", PRIOR + "/source.tar.gz", PRIOR + "/cpu-tests.log",
                 PRIOR + "/ruff.log", DIAG + "/index.json", DOC, SELF, *OWNED):
        add(name)
    check(sha(files[DOC]) == plan["doc_sha256"], "Doc pin mismatch")
    for name, pin in json.loads(files[DIAG + "/index.json"])["files"].items():
        add(DIAG + "/" + name, pin)
    files["publication-plan.json"] = plan_raw
    bindings = {key: plan[key] for key in ("build_manifest_sha256", "unit_report", "mission_report")}
    outcome = semantics(files, bindings)
    # Validate all archive bytes before creating an assembly. No automatic exclusions.
    budget = [0]
    for name, raw in files.items():
        inspect(raw, name, budget)
    stage.mkdir()
    (stage / ".gitattributes").write_bytes(b"* -text -whitespace\n")
    readme = (
        "# GPU mass-merit evidence, v632\n\n"
        "This package preserves the all-node minimum-mass merit change, its native validation, "
        "the matched return experiment, and the preceding saved-only diagnosis. "
        "Full rationale and measured limitations are in `docs/GPU_MASS_MERIT.md` inside `evidence.zip`.\n\n"
        f"Build passed: `{outcome['build_passed']}`. Native validation passed: `{outcome['unit_passed']}`. "
        f"Mission status: `{outcome['mission_status']}`. "
        f"Returned native calls: `{outcome['mission_native_solves_returned']}`; "
        f"outer iterations: `{outcome['mission_native_iterations']}`. "
        "These labels retain failed outcomes; passing native unit tests alone does not certify a mission.\n\n"
        "The fuel objective, cargo, schedule, conic constraints and independent physical/fleet gates are unchanged. "
        "Merit values are dimensionless normalized subproblem costs, not kg. "
        "The source archive is compared against the sealed v631 source: exactly three reviewed CUDA files differ. "
        "Runtime executable/library hashes are retained in manifests; compiled binaries and credentials are excluded.\n\n"
        "Older fleet/prefix inputs and runtime dependencies listed in the mission's `external-evidence.json` "
        "remain hash-linked to the existing repository artifacts. They are not fetched or repackaged here. "
        "The prior v631 source archive/manifest and CPU logs are included only to verify the three-source delta "
        "and unchanged-host validation. This is a saved-byte/source/status verifier, not a fresh mission replay.\n\n"
        "Run `python audit_package.py verify --roundtrip` for saved-byte verification only. "
        "An optional `--index-sha256 HASH` pins the independently supplied index. "
        "The verifier uses only the standard library, checks nested archives and source maps, "
        "and runs no archived code, optimizer, GPU computation, ephemerides, or propagation.\n"
    )
    (stage / "README.md").write_text(readme, encoding="utf-8")
    (stage / "audit_package.py").write_bytes(Path(__file__).read_bytes())
    with zipfile.ZipFile(stage / "evidence.zip", "x", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for name, raw in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2026, 9, 9, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, raw)
    raw = (stage / "evidence.zip").read_bytes()
    index = {"schema": SCHEMA, "archive_sha256": sha(raw), "archive_bytes": len(raw),
             "file_count": len(files), "total_bytes": sum(map(len, files.values())),
             "files": {name: record(data) for name, data in sorted(files.items())}, "bindings": bindings,
             "top_files": {name: record((stage / name).read_bytes()) for name in ("README.md", "audit_package.py", ".gitattributes")},
             "outcome": outcome, "runtime_binaries_included": False,
             "omitted_files": omitted,
             "external_repository_dependencies": json.loads(files[MISSION + "/external-evidence.json"])}
    index_raw = (json.dumps(index, indent=2) + "\n").encode()
    (stage / "index.json").write_bytes(index_raw)
    result = verify(stage, sha(index_raw), roundtrip=True)
    verification = stage.parent / "verification.json"
    with verification.open("x") as stream:
        json.dump(result, stream, indent=2)
        stream.write("\n")
    final.parent.mkdir(parents=True, exist_ok=True)
    check(not final.exists(), "Final appeared during assembly")
    # Recheck resolved absolute targets immediately before the directory move.
    # Both must remain at the intended locations inside this repository.
    check(stage.resolve() == root / "build/performance/gpu-mass-merit-v632-publish/assembly"
          and final.resolve() == root / FINAL
          and root in stage.resolve().parents and root in final.resolve().parents,
          "Resolved assembly/final paths escaped their intended repository locations")
    os.rename(stage, final)
    return {"package": FINAL, **result}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    b = sub.add_parser("build")
    b.add_argument("--root", type=Path, required=True)
    b.add_argument("--plan", type=Path, required=True)
    v = sub.add_parser("verify")
    v.add_argument("--package", type=Path, default=Path(__file__).resolve().parent)
    v.add_argument("--index-sha256")
    v.add_argument("--roundtrip", action="store_true")
    args = parser.parse_args()
    result = build(args.root.resolve(), args.plan) if args.action == "build" else verify(args.package, args.index_sha256, args.roundtrip)
    print(json.dumps(result, indent=2))
